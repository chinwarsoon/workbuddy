// build.mjs - packages src/xlsx-reader.mjs, src/pipeline.mjs and src/render.mjs into the
// single offline Procurement-Dashboard.html. The delivered page must run from file:// with
// no server, no import and no external reference.
// Revision 1.0 - 2026-10-30 - opencode (AI): first pipeline build (I-76, P1).
// Revision 1.1 - 2026-10-30 - opencode (AI): normalise the written file to CRLF so the shell and the generated block use one line ending.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const files = ['xlsx-reader.mjs', 'pipeline.mjs', 'render.mjs'];

let code = '';
for (const f of files) {
  let text = fs.readFileSync(path.join(dir, 'src', f), 'utf8');
  const ticks = (text.match(/`/g) || []).length;
  if (ticks % 2) {
    console.error('BUILD FAILED - ' + f + ': odd number of backticks (unterminated template literal).');
    process.exit(1);
  }
  text = text
    .split('\n')
    .filter((l) => !/^\s*import\s/.test(l))
    .map((l) => l.replace(/^export\s+/, ''))
    .join('\n');
  code += '\n/* ===== ' + f + ' ===== */\n' + text + '\n';
}

const bundle = '/* All app code lives inside one IIFE (I-33) so nothing leaks onto the global\n' +
  '   scope. Generated by build.mjs from src/ - do not edit this block by hand. */\n' +
  '(function(){\n' + code + '\nboot();\n})();\n';

try {
  new vm.Script(bundle, { filename: 'bundle.js' });
} catch (e) {
  console.error('BUILD FAILED - assembled bundle does not parse:\n' + e.stack);
  process.exit(1);
}

const htmlPath = path.join(dir, 'Procurement-Dashboard.html');
let html = fs.readFileSync(htmlPath, 'utf8');
const open = html.indexOf('<script>');
const close = open < 0 ? -1 : html.indexOf('</script>', open);
if (open < 0 || close < 0) {
  console.error('BUILD FAILED - no inline <script> block found in Procurement-Dashboard.html.');
  process.exit(1);
}
html = (html.slice(0, open) + '<script>\n' + bundle + '</script>' + html.slice(close + '</script>'.length))
  .replace(/\r\n/g, '\n')
  .replace(/\n/g, '\r\n');
fs.writeFileSync(htmlPath, html, 'utf8');
console.log('Wrote', htmlPath, '(' + html.length + ' bytes, ' + bundle.split('\n').length + ' bundle lines)');
